/* БЛОК: Сводка по аудиту (countAudit)
 * ЗА ЧТО ОТВЕЧАЕТ: Считает число проблем по приоритетам и сколько уже закрыто.
 * ОТКУДА БЕРЁТ ИНФОРМАЦИЮ: SITE_AUDIT выше.
 * КАК ИЗМЕНИТЬ: Не требуется. */
export function countAudit(): {
  total: number;
  critical: number;
  important: number;
  minor: number;
  done: number;
} {
  const counts = { total: SITE_AUDIT.length, critical: 0, important: 0, minor: 0, done: 0 };
  for (const item of SITE_AUDIT) {
    counts[item.priority] += 1;
    if (item.status === "done") counts.done += 1;
  }
  return counts;
}
